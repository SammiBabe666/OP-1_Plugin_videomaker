"""Compile a plugin's own C sources together with the host simulator into a small program, op1sim.

Each plugin source is compiled in its own translation unit, as the firmware build does, through a wrapper that
also exports that unit's beat clock (op1_plugin.h keeps one static clock per unit on the host). Results are cached
under .cache/build/<plugin>-<hash>/ so a plugin is only rebuilt when its sources, the simulator or flags change.
"""
from __future__ import annotations

import hashlib
import os
import shlex
import shutil
import subprocess
from pathlib import Path

from . import compat
from .sdk import Plugin, cache_dir, synth_sdk

ROOT = Path(__file__).resolve().parent.parent
SIM = ROOT / "sim"
SIM_FILES = [SIM / "driver.c", SIM / "host.c", SIM / "include" / "harness" / "op1_host.h"]
# -fwrapv: the DSP code relies on two's-complement wrap-around (phase accumulators, Q15 maths), as on the
# Blackfin; -fno-strict-aliasing: firmware-style pointer casts.
BASE_FLAGS = ["-std=gnu11", "-O2", "-fwrapv", "-fno-strict-aliasing", "-DOP1_HOST"]
# flags in plugin.json meant for the Blackfin toolchain that a host compiler may not accept
DROP_FLAGS = {"-mcpu=bf524", "-mcsync-anomaly", "-mspecld-anomaly", "-mfast-fp", "-mlow64k"}


class BuildError(RuntimeError):
    pass


def compiler() -> str:
    cc = os.environ.get("CC")
    if cc:
        return cc
    for c in ("cc", "gcc", "clang"):
        if shutil.which(c):
            return c
    raise BuildError("no C compiler found: install gcc or clang (see docs/INSTALL.md), or set CC")


def kind_define(p: Plugin) -> str:
    return {"synth": "-DOP1V_KIND_SYNTH", "fx": "-DOP1V_KIND_FX", "input": "-DOP1V_KIND_INPUT"}[p.kind]


def _plugin_flags(p: Plugin) -> list[str]:
    flags = [f for f in p.cflags if f not in DROP_FLAGS and not f.startswith("-mcpu")]
    for inc in p.include_dirs:
        flags.append("-I" + str((p.dir / inc).resolve()))
    return flags


def compat_file(p: Plugin) -> Path:
    """Optional per-plugin host glue (sim/compat/<plugin>.c) for plugins that ship their own preview hooks."""
    return SIM / "compat" / f"{p.name}.c"


def _fingerprint(p: Plugin, cc: str, extra: list[str]) -> str:
    h = hashlib.sha256()
    h.update(cc.encode())
    h.update(" ".join(BASE_FLAGS + extra + _plugin_flags(p)).encode())
    h.update(repr(compat.patched_sources(p.name)).encode())
    for f in SIM_FILES + [compat_file(p)]:
        if f.exists():
            h.update(f.read_bytes())
    for f in sorted(p.dir.rglob("*")):
        if f.is_file() and f.suffix in (".c", ".h", ".S", ".inc", ".json"):
            h.update(str(f.relative_to(p.dir)).encode())
            h.update(f.read_bytes())
    return h.hexdigest()[:16]


def build(p: Plugin, sdk_root: Path, verbose: bool = False, force: bool = False, extra: list[str] | None = None) -> Path:
    """Return the path of op1sim for plugin `p`, compiling it if needed."""
    extra = list(extra or [])
    cc = compiler()
    out_dir = cache_dir() / "build" / f"{p.name}-{_fingerprint(p, cc, extra)}"
    exe = out_dir / "op1sim"
    if exe.exists() and not force:
        return exe
    if out_dir.exists():
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True)

    sdk = synth_sdk(sdk_root)
    includes = [f"-I{SIM / 'include'}", f"-I{sdk}", f"-I{p.dir}"]
    defines = [kind_define(p), f"-DOP1V_SYMBOL={p.symbol}"]
    if p.screen_symbol:
        defines.append(f"-DOP1V_SCREEN={p.screen_symbol}")
    common = BASE_FLAGS + includes + _plugin_flags(p) + extra

    units: list[tuple[Path, list[str]]] = []
    c_sources = [s for s in p.sources if s.endswith(".c")]
    skipped = [s for s in p.sources if not s.endswith(".c")]
    if skipped and verbose:
        print(f"  note: skipping non-C sources (device-only assembly): {', '.join(skipped)}")
    patches = compat.patched_sources(p.name)
    for i, src in enumerate(c_sources):
        path = (p.dir / src).resolve()
        if src in patches:                      # exact-match host fixes (compat.py), applied to a copy
            pdir = out_dir / "patched"
            pdir.mkdir(exist_ok=True)
            try:
                text = compat.apply(p.name, src, path.read_text())
            except compat.PatchError as e:
                raise BuildError(str(e))
            path = pdir / Path(src).name
            path.write_text(text)
        w = out_dir / f"unit{i}.c"
        w.write_text(
            f'/* generated by op1video: plugin source {src} plus its beat-clock accessor */\n'
            f'#include "{path}"\n'
            '#include "op1_plugin.h"\n'
            f'op1_beat_t *op1v_beat_{i}(void) {{ return host_beat(); }}\n')
        units.append((w, ["-w"]))
    beats = out_dir / "beats.c"
    n = len(c_sources)
    decl = "".join(f"op1_beat_t *op1v_beat_{i}(void);\n" for i in range(n))
    table = ", ".join(f"op1v_beat_{i}" for i in range(n)) or "0"
    beats.write_text('#include "op1_plugin.h"\n' + decl +
                     f"op1_beat_t *(*const op1v_beats[])(void) = {{ {table} }};\n"
                     f"const int op1v_nbeats = {n};\n")
    units.append((beats, []))
    units.append((SIM / "host.c", ["-Wall", "-Wno-unused-function"]))
    if compat_file(p).exists():
        units.append((compat_file(p), ["-Wall"]))
    units.append((SIM / "driver.c", ["-Wall", "-Wno-unused-function"] + defines))

    objs = []
    for src, flags in units:
        obj = out_dir / (src.stem + ".o")
        cmd = [cc, *common, *flags, "-c", str(src), "-o", str(obj)]
        _run(cmd, verbose, f"compiling {src.name} for {p.name}")
        objs.append(str(obj))
    _run([cc, *objs, "-lm", "-o", str(exe)], verbose, f"linking {p.name}")
    return exe


def _run(cmd: list[str], verbose: bool, what: str) -> None:
    if verbose:
        print("  $ " + " ".join(shlex.quote(c) for c in cmd))
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        msg = (r.stderr or r.stdout).strip()
        lines = [l for l in msg.splitlines() if "error" in l.lower() or "undefined reference" in l or "multiple definition" in l] or msg.splitlines()
        raise BuildError(f"{what} failed:\n" + "\n".join(lines[:25]))
